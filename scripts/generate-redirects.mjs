// Writes public/_redirects for Cloudflare Pages. /latest/<minecraft version> always points to the newest file
// found in public/downloads/<version>/ (same rules as src/lib/releases.ts).
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const data = JSON.parse(readFileSync(new URL('src/data/releases.json', root), 'utf8'));
const mcs = Object.keys(data.targets).sort((a, b) => b.length - a.length);
const dl = new URL('public/downloads/', root);
const cmp = (a, b) => {
  const pa = a.split('.').map(Number), pb = b.split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) if ((pb[i] ?? 0) !== (pa[i] ?? 0)) return (pb[i] ?? 0) - (pa[i] ?? 0);
  return 0;
};
const mcOf = (n) => mcs.find((v) => new RegExp(`(^|[^0-9.])(mc)?${v.replace(/\./g, '\\.')}(\\.jar$|[^0-9])`, 'i').test(n));

const latest = {};
const useLocal = (data.external ?? []).length === 0;
const versions = useLocal && existsSync(dl) ? readdirSync(dl).filter((v) => /^\d+(\.\d+)*$/.test(v) && statSync(new URL(v, dl)).isDirectory()).sort(cmp) : [];
for (const v of versions) {
  for (const f of readdirSync(new URL(v + '/', dl))) {
    const mc = f.toLowerCase().endsWith('.jar') && mcOf(f);
    if (mc && !latest[mc]) latest[mc] = `/downloads/${encodeURIComponent(v)}/${encodeURIComponent(f)}`;
  }
}
for (const e of data.external ?? []) {
  if (!latest[e.mc] || cmp(e.version, versions.find((v) => latest[e.mc].includes(`/${v}/`)) ?? '0') < 0) latest[e.mc] = e.url;
}

const lines = [
  '# Generated by scripts/generate-redirects.mjs – do not edit.',
  '/download /downloads/ 301',
  '/download/ /downloads/ 301',
  '/impressum /imprint/ 301',
  '/impressum/ /imprint/ 301',
  '/datenschutz /privacy/ 301',
  '/datenschutz/ /privacy/ 301',
  '/discord https://discord.gg/mariomods 302',
  ...Object.entries(latest).map(([mc, href]) => `/latest/${mc} ${href} 302`),
];
writeFileSync(new URL('public/_redirects', root), lines.join('\n') + '\n');
console.log('_redirects written:', JSON.stringify(latest));
